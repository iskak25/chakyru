export function formatInviteDate(date: string, locale: string) {
  if (!date) return "";
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date.trim());
  if (!match) return date;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  if (month < 1 || month > 12 || day < 1 || day > 31) return date;
  if (locale === "ru") return `${day} ${RU_MONTHS[month - 1]} ${year} г.`;
  return `${year}-ж., ${day}-${KY_MONTHS[month - 1]}`;
}

export function formatInviteDay(iso: string) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "";
  const day = String(d.getDate()).padStart(2, "0");
  const month = String(d.getMonth() + 1).padStart(2, "0");
  return `${day}.${month}.${d.getFullYear()}`;
}

export function formatPrice(locale: Locale, som: number) {
  if (som === 0) return locale === "ru" ? "Бесплатно" : "Акысыз";
  return `${som.toLocaleString("ru-RU")} сом`;
}

export function planPrice(locale: Locale, plan: "standard" | "pro" | "unlimited") {
  const table = {
    ky: { standard: "990 сом", pro: "1 990 сом", unlimited: "2 990 сом" },
    ru: { standard: "990 сом", pro: "1 990 сом", unlimited: "2 990 сом" },
  };
  return table[locale][plan];
}
